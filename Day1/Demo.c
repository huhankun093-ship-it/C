#include <stdio.h>
#include <string.h>

int main() 
{
    int len = strlen("abc"); //strlen() is a function that returns the length of a string.
    printf("len = %d\n", len); //%d is a placeholder for an integer. placeholder means a place to put something.\n makes a new line.
    printf("Hello World!\n");
    printf("%d\n", strlen("c:\test\628\test.c"));//\628 is a octal number, which is a number in base 8. It is used to represent characters in C. \t is a tab character.

    return 0;
}

















